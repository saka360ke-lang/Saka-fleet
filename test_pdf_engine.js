/**
 * Saka Fleet — PDF engine glyph-safety, Apex components & structure tests (v1.29.0)
 * --------------------------------------------------------------------------------
 * Offline. Proves the Saka Apex renderer produces a valid PDF even when the
 * report data contains WhatsApp emoji and Unicode symbols (the cause of the
 * "boxes / illegible" reports), that the sanitiser never leaks a glyph the
 * embedded fonts cannot draw, and that ledgers, badges, segmented bars, vs bars
 * and callouts draw real, readable content (standard-font preview mode).
 *
 * Run: node test_pdf_engine.js
 */

import assert from 'assert';
import { buildProReportPdf, pdfSafeText, getReportAccent, SAKA_PDF_THEME } from './src/services/pdfEngine.js';
import { extractPdfText } from './src/services/pdfTextExtractor.js';
import { complianceReportToPdf, fleetReportToPdf } from './src/services/reportDelivery.js';

let passed = 0;
function check(condition, label) {
  assert.ok(condition, label);
  passed += 1;
  console.log(`  ✅ ${label}`);
}

async function run() {
  console.log('=== SAKA FLEET — PDF ENGINE TESTS (v1.29.0) ===\n');

  console.log('--- Test 1: glyph sanitiser ---');
  check(pdfSafeText('⛽ Fuel — 40 L ✓') === 'Fuel - 40 L ok', 'Emoji removed, em dash and check mapped to ASCII');
  check(pdfSafeText('→ 12,000 km · ≥ 80%') === '-> 12,000 km - >= 80%', 'Arrows, bullets and comparators mapped');
  check(pdfSafeText('Café Zürich') === 'Café Zürich', 'Latin-1 accents are preserved (never mangled)');
  check(pdfSafeText('مرحبا 你好') === '', 'Non-Latin scripts are dropped instead of rendering as tofu');
  check(pdfSafeText('A\n\n\n\nB') === 'A\n\nB', 'Runaway blank lines collapse');
  check(pdfSafeText(null) === '' && pdfSafeText(undefined) === '', 'Nullish values are safe');
  check(!/[\u{1F000}-\u{1FAFF}]/u.test(pdfSafeText('🔔 Service due 🚨')), 'No pictographs survive sanitisation');

  console.log('\n--- Test 2: theme + accents ---');
  check(getReportAccent('fuel_economy') === SAKA_PDF_THEME.accents.fuel_economy, 'Report type accent resolves');
  check(getReportAccent('unknown-type') === SAKA_PDF_THEME.accents.default, 'Unknown report types fall back to the default accent');

  console.log('\n--- Test 3: full report renders a valid PDF (emoji-heavy data) ---');
  const report = {
    title: '🚗 Fleet Report — November',
    subtitle: 'Fuel ⛽, costs 💰 and compliance ✓',
    reportType: 'fleet',
    periodLabel: '1 – 30 Nov 2026',
    owner: { name: 'Daudi Mwangi 🇰🇪', phone: '+254700000001' },
    drivers: [{ name: 'Amina', plate: 'KDA 123A', status: 'active' }],
    kpis: [
      { label: 'Vehicles 🚗', value: '3', hint: 'in scope' },
      { label: 'Fuel spend ⛽', value: 'KES 48,500', hint: 'this month' },
      { label: 'Distance →', value: '12,450 km', hint: '≈ 1,200 L' }
    ],
    charts: [
      { type: 'bar', title: 'Monthly fuel ⛽', labels: ['Sep', 'Oct', 'Nov'], values: [42000, 46000, 48500], currency: 'KES' },
      { type: 'donut', title: 'Cost split 💰', labels: ['Fuel', 'Service'], values: [70, 30] },
      { type: 'line', title: 'Odometer', labels: ['W1', 'W2', 'W3'], values: [120000, 121200, 124500] },
      { type: 'progress', title: 'Health 🟢', value: 82, max: 100 }
    ],
    tables: [{
      title: 'Vehicles 🚚',
      columns: [
        { key: 'plate', label: 'Plate' },
        { key: 'km', label: 'Distance', type: 'number', align: 'right' },
        { key: 'cost', label: 'Spend', type: 'money', align: 'right' },
        { key: 'status', label: 'Status', type: 'status' }
      ],
      rows: [
        { plate: 'KDA 123A', km: 12450, cost: 48500, status: 'good' },
        { plate: 'KDB 456B ✓', km: 8200, cost: 21000, status: 'warn' }
      ],
      currency: 'KES'
    }],
    sections: [{
      title: 'People & roles 👤',
      rows: [
        { label: 'Owner', value: 'Daudi Mwangi' },
        { label: 'Driver — KDA 123A', value: 'Amina', status: 'good' }
      ],
      lines: ['Trip → 370,000 km next service 🔔', 'No data missing ✓']
    }],
    notes: ['Generated by Saka Fleet on 1 Nov 2026 — Africa/Nairobi', 'Figures are engine-calculated ⚙️']
  };

  const buffer = await buildProReportPdf(report);
  check(Buffer.isBuffer(buffer) && buffer.length > 3000, `PDF buffer is generated (${buffer.length} bytes)`);
  check(buffer.slice(0, 5).toString() === '%PDF-', 'Starts with a valid %PDF header');
  check(buffer.includes(Buffer.from('%%EOF')), 'Ends with a complete %%EOF trailer');
  const pages = buffer.toString('latin1').match(/\/Type\s*\/Page[^s]/g) || [];
  check(pages.length >= 1, `Contains at least one page object (${pages.length})`);

  console.log('\n--- Test 4: empty/minimal report never throws ---');
  const minimal = await buildProReportPdf({ title: 'Saka', reportType: 'custom' });
  check(Buffer.isBuffer(minimal) && minimal.slice(0, 5).toString() === '%PDF-', 'Minimal report still renders a valid PDF');
  const nullish = await buildProReportPdf({ title: null, kpis: [{ label: null, value: null }], tables: [{ columns: [{ key: 'x', label: null }], rows: [{ x: null }] }] });
  check(Buffer.isBuffer(nullish) && nullish.length > 1000, 'Nullish fields degrade gracefully');

  console.log('\n--- Test 5: Apex components render real content ---');
  const apexReport = {
    title: 'Apex Component Proof',
    subtitle: 'Ledger, badges, segments, vs bars and callouts',
    reportType: 'vehicle_deep_dive',
    plate: 'KAS 628T',
    useStandardFonts: true,
    kpis: [
      { label: 'Real zero spend', value: 'KES 0', hint: 'surfaced, never hidden', tone: 'negative' },
      { label: 'Earnings', value: 'KES 12,000', hint: 'surplus', tone: 'positive' }
    ],
    charts: [
      {
        type: 'segment',
        title: 'Spend split',
        currency: 'KES',
        segments: [{ label: 'Fuel', value: 7000 }, { label: 'Service', value: 3000 }]
      },
      { type: 'vs', title: 'Earnings vs expenses', currency: 'KES', earnings: 12000, expenses: 10000 },
      { type: 'segment', title: 'Empty split', currency: 'KES', segments: [{ label: 'None', value: 0 }] }
    ],
    ledgers: [{
      title: 'Itemized activity & ledger',
      currency: 'KES',
      groups: [{
        label: 'November 2026',
        expenseTotal: 10000,
        earningTotal: 12000,
        rows: [
          { date: '2 Nov 2026', kind: 'fuel', kindLabel: 'FUEL', description: 'Fuel - 45 L', odometer: 50350, unitCost: 133.33, amount: 6000 },
          { date: '3 Nov 2026', kind: 'earning', kindLabel: 'EARNING', description: 'Daily earnings', odometer: 50380, unitCost: null, amount: 12000 },
          { date: '4 Nov 2026', kind: 'maintenance', kindLabel: 'SERVICE', description: 'Brake pads', odometer: null, unitCost: null, amount: 4000 }
        ]
      }],
      totals: { scanned: 3, shown: 3, expenseTotal: 10000, earningTotal: 12000, net: 2000 }
    }],
    callouts: [{ tone: 'positive', title: 'Financial health', body: 'Surplus of KES 2,000 after all recorded costs.' }],
    tables: [{
      title: 'Zero vs missing proof',
      currency: 'KES',
      columns: [
        { key: 'realZero', label: 'Real zero', type: 'money', align: 'right' },
        { key: 'missing', label: 'Missing', type: 'money', align: 'right' }
      ],
      rows: [{ realZero: 0, missing: null }]
    }]
  };
  const apexBuffer = await buildProReportPdf(apexReport);
  const apexPages = (apexBuffer.toString('latin1').match(/\/Type\s*\/Page[^s]/g) || []).length;
  check(apexBuffer.slice(0, 5).toString() === '%PDF-', 'Apex report renders a valid PDF');
  check(apexPages >= 3, `Apex report spans the cover + content + ledger pages (${apexPages})`);
  const apexText = String(extractPdfText(apexBuffer).text || '').toLowerCase();
  check(apexText.includes('kas 628t'), 'Plate badge text is drawn on the cover');
  check(apexText.includes('itemized activity'), 'Ledger section title is drawn');
  check(apexText.includes('fuel'), 'Ledger FUEL badge is drawn');
  check(apexText.includes('earning'), 'Ledger EARNING badge is drawn');
  check(apexText.includes('odometer'), 'Ledger column headers are drawn');
  check(apexText.includes('total'), 'Ledger TOTAL band is drawn');
  check(apexText.includes('nothing hidden'), 'Transparency footer is drawn');
  check(apexText.includes('kes 0'), 'A real numeric zero renders as an explicit KES 0');
  check(!apexText.includes('kes -'), 'A missing amount never renders as a currency figure');
  check(apexText.includes('no activity recorded'), 'An empty segmented chart degrades with plain copy');
  check(apexText.includes('financial health'), 'Insight callouts are drawn');
  check(apexText.includes('recorded costs'), 'Callout body copy is drawn');

  console.log('\n--- Test 6: compliance report is itemized (v1.32.3) ---');
  const compliancePayload = complianceReportToPdf({
    ok: true,
    type: 'compliance',
    data: {
      generatedAt: '2026-11-01T09:30:00.000Z',
      currency: 'KES',
      vehicles: [{ plate: 'KAS 628T', make_model: 'Toyota Fielder', asset_kind: 'car', status: 'active' }],
      insuranceStatusMatrix: { total: 3, active: 1, due30: 0, due14: 0, due7: 0, expired: 1, items: [] },
      inspectionAndPermits: {
        inspections: { total: 2, active: 1, due30: 1, due14: 0, due7: 0, expired: 0, items: [] },
        permits: { total: 2, active: 2, due30: 0, due14: 0, due7: 0, expired: 0, items: [] },
        licensing: { total: 0, active: 0, due30: 0, due14: 0, due7: 0, expired: 0, items: [] }
      },
      driverLicenses: { total: 0, active: 0, due30: 0, expired: 0, items: [] },
      driverCompliance: [],
      notificationLog: [],
      actionPrompt: [],
      expiryItems: [
        { plate: 'KAS 628T', category: 'insurance', categoryLabel: 'Insurance', item: 'Insurance Renewal', dueDate: '2026-09-30', daysLeft: -32, status: 'expired' },
        { plate: 'KAS 628T', category: 'inspection', categoryLabel: 'Inspection', item: 'Inspection', dueDate: '2026-11-18', daysLeft: 17, status: 'due_30d' },
        { plate: 'KAS 628T', category: 'permit', categoryLabel: 'Permit', item: 'Permit', dueDate: '2027-01-14', daysLeft: 74, status: 'active' }
      ],
      documents: [
        { plate: 'KAS 628T', type: 'insurance', label: 'Insurance', number: 'POL-8871-KE', expiry: '2026-09-30', daysLeft: -32, status: 'expired' },
        { plate: 'KAS 628T', type: 'inspection', label: 'Inspection', number: 'INS-5521', expiry: '2026-11-18', daysLeft: 17, status: 'due_30d' }
      ],
      totals: { monitored: 7, active: 4, expiring30Days: 1, expiring7Days: 0, expired: 1 }
    }
  }, 'compliance');
  check(compliancePayload.kpis.length === 4, 'Compliance cover shows four KPI cards');
  check(compliancePayload.coverHighlights.length === 3, 'Compliance cover carries the highlight row');
  const itemTable = compliancePayload.tables.find((table) => /upcoming/i.test(table.title));
  check(Boolean(itemTable) && itemTable.rows.length === 3, 'Every monitored item is itemized (not summarized)');
  check(itemTable.rows[0].status === 'Expired' && itemTable.rows[0].daysLeft === '32d overdue', 'The expired item leads with its real overdue age');
  check(itemTable.columns.some((column) => column.key === 'expires'), 'Itemized rows carry an expiry column');
  const docTable = compliancePayload.tables.find((table) => /documents on file/i.test(table.title));
  check(Boolean(docTable) && docTable.rows[0].number === 'POL-8871-KE', 'Policy numbers are listed for documents on file');
  check(compliancePayload.sections.some((section) => /category matrix/i.test(section.title)), 'Category matrix section is present');
  check(!compliancePayload.sections.some((section) => /Road licence/.test(JSON.stringify(section.rows || []))), 'All-zero categories are collapsed out of the matrix');

  const complianceBuffer = await buildProReportPdf({ ...compliancePayload, useStandardFonts: true });
  const complianceText = String(extractPdfText(complianceBuffer).text || '').toLowerCase();
  const compliancePages = (complianceBuffer.toString('latin1').match(/\/Type\s*\/Page[^s]/g) || []).length;
  check(complianceBuffer.slice(0, 5).toString() === '%PDF-', 'Compliance report renders a valid PDF');
  check(compliancePages >= 2, `Compliance report spans cover + itemized pages (${compliancePages})`);
  check(complianceText.includes('kas 628t'), 'Plate is drawn on the compliance cover');
  check(complianceText.includes('32d overdue'), 'Overdue age is drawn in the itemized table');
  check(complianceText.includes('expired'), 'Expired status is drawn');
  check(complianceText.includes('documents on file'), 'Documents-on-file panel is drawn');
  check(complianceText.includes('pol-8871-ke'), 'Policy number is drawn');
  check(complianceText.includes('category matrix'), 'Category matrix panel is drawn');
  check(complianceText.includes('reminder ladder'), 'Provenance notes are drawn');
  check(!complianceText.includes('road licence'), 'A zero-count category never renders as a row');

  // Regression: every other report type keeps the generic summary-led layout.
  const fleetPayload = fleetReportToPdf({
    ok: true,
    text: '*Fleet Status Report*\n_1 Nov 2026_\n• Vehicles: 2\n• Active: 2',
    data: { currency: 'KES', overview: { totalVehicles: 2, activeVehicles: 2, activeDrivers: 1 } }
  }, 'fleet');
  check(fleetPayload.title === 'Fleet Status Report', 'Non-compliance reports keep their generic title');
  check(!fleetPayload.coverHighlights, 'Non-compliance reports carry no compliance highlight row');
  const fleetBuffer = await buildProReportPdf({ ...fleetPayload, useStandardFonts: true });
  check(fleetBuffer.slice(0, 5).toString() === '%PDF-', 'Non-compliance reports still render');

  console.log(`\n🎉 ${passed} PDF engine assertions passed.`);
}

run().catch((err) => {
  console.error('\n❌ PDF engine suite failed:', err.message);
  process.exit(1);
});
