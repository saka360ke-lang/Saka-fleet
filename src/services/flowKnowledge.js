/** Compact prompt block — injected into Saka's core system prompt. */
export function buildFlowPlaybook() {
  const quizLines = SAKA_QUIZ_FLOWS.map(
    (f) => `- ${f.key} (${f.label}): trigger ${f.trigger}. Order: ${f.fields}. Extracted keys: ${f.extracted.length ? f.extracted.join(', ') : 'none'}. Writes after confirm: ${f.writes}. Rules: ${f.rules}.`
  );
  const intentLines = SAKA_INTENT_PLAYBOOK.map((i) => `- ${i.intent}: ${i.behavior}`);
  return [
    'SAKA FLOW PLAYBOOK (authoritative — every flow must be handled exactly like this):',
    'QUIZ FLOWS (one question per turn; summary + explicit confirmation before any write):',
    ...quizLines,
    'NON-QUIZ INTENTS:',
    ...intentLines,
    'BOUNDARIES:',
    ...SAKA_BOUNDARY_RULES.map((r) => `- ${r}`)
  ].join('\n');
}

export function getKnownFlowKeys() {
  return SAKA_QUIZ_FLOWS.map((f) => f.key);
}

export function getKnownIntents() {
  return [...SAKA_INTENTS];
}

